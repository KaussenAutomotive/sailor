const { test } = require('node:test');
const assert = require('node:assert/strict');
const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');

test('desktop: offline rendering, parameters, native save/open, validation and PNG export', { timeout: 90000 }, async () => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'sailor-desktop-test-'));
  const profile = path.join(folder, 'profile');
  const designFile = path.join(folder, 'test.sailor.json');
  const imageFile = path.join(folder, 'preview.png');
  const stepFile = path.join(folder, 'model.step');
  let desktop;
  const launchOptions = {
    ...(process.env.SAILOR_EXECUTABLE ? { executablePath: process.env.SAILOR_EXECUTABLE } : {}),
    args: [...(process.env.SAILOR_EXECUTABLE ? [] : [path.resolve(__dirname, '..')]), `--user-data-dir=${profile}`],
    env: { ...process.env, ELECTRON_RUN_AS_NODE: undefined },
  };
  try {
    desktop = await _electron.launch(launchOptions);
    const userData = await desktop.evaluate(({ app }) => app.getPath('userData'));
    assert.equal(path.resolve(userData).toLowerCase(), path.resolve(profile).toLowerCase(), 'Tests must use an isolated profile');
    const page = await desktop.firstWindow();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('canvas');
    await page.getByRole('textbox', { name: 'Entwurfsname' }).fill('Desktop Test');
    await page.getByRole('button', { name: 'Katamaran', exact: true }).click();
    const mass = page.getByRole('slider', { name: 'Gesamtmasse', exact: true });
    assert.equal(await mass.getAttribute('max'), '10');
    await mass.press('End');
    assert.equal(await mass.inputValue(), '10');
    await mass.fill('4');
    await page.getByRole('slider', { name: 'Länge Backbordrumpf', exact: true }).fill('0.8');
    await page.getByRole('slider', { name: 'Länge Steuerbordrumpf', exact: true }).fill('1.2');
    await page.getByRole('button', { name: 'Segel', exact: true }).click();
    await page.getByRole('button', { name: 'Square Top Breiter Segelkopf' }).click();
    const jib = page.getByRole('slider', { name: 'Vorsegel / Fock' });
    await jib.press('Home');
    assert.equal(await jib.inputValue(), '0');
    await page.getByRole('button', { name: 'Foils', exact: true }).click();
    await page.getByRole('switch', { name: 'Hydrofoils aktivieren' }).click();
    await page.getByRole('button', { name: 'V-Foil', exact: true }).click();
    await page.getByRole('combobox', { name: 'Flügelumriss' }).selectOption('elliptic');
    const span = page.getByRole('slider', { name: 'Foil-Spannweite' });
    await span.press('End');
    await page.getByRole('region', { name: 'Hydrofoil-Wirkung' }).waitFor();
    await page.getByRole('button', { name: 'Foil-Detail', exact: true }).click();
    assert.match(await page.locator('.viewport-caption').innerText(), /WASSER AUSGEBLENDET/);
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename });
    }, designFile);
    await page.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
    await page.getByRole('button', { name: 'Gespeichert', exact: true }).waitFor();
    const saved = JSON.parse(await fs.readFile(designFile, 'utf8'));
    assert.equal(saved.name, 'Desktop Test');
    assert.equal(saved.type, 'cat');
    assert.equal(saved.sailShape, 'square');
    assert.equal(saved.jibArea, 0);
    assert.equal(saved.foils.enabled, true);
    assert.equal(saved.foils.type, 'V');
    assert.equal(saved.foils.planform, 'elliptic');
    assert.equal(saved.foils.span, 0.6);
    assert.deepEqual(saved.hullLengths, [0.8, 1.2]);
    assert.equal(saved.length, 1.2);
    assert.equal(saved.mass, 4);

    const malformedFile = path.join(folder, 'invalid.json');
    await fs.writeFile(malformedFile, JSON.stringify({ ...saved, mastHeight: 999 }));
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] });
    }, malformedFile);
    await page.getByRole('button', { name: 'Entwurf öffnen', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.match(await page.getByRole('alert').innerText(), /Ungültiger Wert/);
    assert.equal(await page.getByRole('textbox', { name: 'Entwurfsname' }).inputValue(), 'Desktop Test');
    await page.getByRole('button', { name: 'Meldung schließen' }).click();

    await page.getByRole('textbox', { name: 'Entwurfsname' }).fill('Changed');
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] });
    }, designFile);
    await page.getByRole('button', { name: 'Entwurf öffnen', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Entwurfsname"]').value === 'Desktop Test');
    assert.equal(await span.inputValue(), '0.6');
    await page.getByRole('button', { name: 'Strömung', exact: true }).click();
    await page.getByRole('region', { name: 'Strömungsanalyse', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Strömungsanalyse"]')?.getAttribute('aria-busy') === 'false');
    assert.match(await page.getByRole('region', { name: 'Strömungsanalyse', exact: true }).locator('.analysis-stats').innerText(), /Gesamtwiderstand/);
    await page.getByRole('button', { name: 'CAD', exact: true }).click();
    await page.getByRole('slider', { name: 'Wandstärke' }).fill('1.2');
    await page.getByRole('combobox', { name: 'Auflösung' }).selectOption('coarse');
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename });
    }, stepFile);
    await page.getByRole('button', { name: 'STEP exportieren', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'STEP exportiert' }).waitFor();
    const step = await fs.readFile(stepFile, 'utf8');
    assert.ok(step.startsWith('ISO-10303-21;'));
    assert.equal((step.match(/MANIFOLD_SOLID_BREP/g) || []).length, 2);
    assert.match(step, /SI_UNIT\(\.MILLI\.,\.METRE\.\)/);
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename });
    }, imageFile);
    await page.getByRole('button', { name: 'Bildexport', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '3D-Ansicht als PNG exportiert' }).waitFor();
    const png = await fs.readFile(imageFile);
    assert.equal(png.subarray(1, 4).toString(), 'PNG');
    assert.ok(png.length > 10000, 'Rendered image should contain a real boat scene');
    assert.equal(await page.locator('.scene-error').count(), 0);
    assert.deepEqual(errors, []);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Desktop layout must fit the window');
    await page.waitForFunction(() => {
      const stored = localStorage.getItem('sailor-studio.design.v1');
      return stored !== null && JSON.parse(stored).name === 'Desktop Test';
    });
    await desktop.close();
    desktop = await _electron.launch(launchOptions);
    const restored = await desktop.firstWindow();
    await restored.waitForFunction(() => document.querySelector('[aria-label="Entwurfsname"]')?.value === 'Desktop Test');
    assert.match(await restored.locator('.design-title small').innerText(), /Katamaran/);
    assert.equal(await restored.getByRole('slider', { name: 'Länge Backbordrumpf', exact: true }).inputValue(), '0.8');
    assert.equal(await restored.getByRole('slider', { name: 'Länge Steuerbordrumpf', exact: true }).inputValue(), '1.2');
    await restored.getByRole('button', { name: 'Segel', exact: true }).click();
    assert.equal(await restored.getByRole('slider', { name: 'Vorsegel / Fock' }).inputValue(), '0');
    await restored.getByRole('button', { name: 'Foils', exact: true }).click();
    assert.equal(await restored.getByRole('slider', { name: 'Foil-Spannweite' }).inputValue(), '0.6');
    await restored.getByRole('button', { name: 'CAD', exact: true }).click();
    assert.equal(await restored.getByRole('slider', { name: 'Wandstärke' }).inputValue(), '1.2');
    await restored.getByRole('button', { name: 'Foils', exact: true }).click();
    assert.equal(await restored.getByRole('switch', { name: 'Hydrofoils aktivieren' }).getAttribute('aria-checked'), 'true');
    await restored.getByRole('button', { name: /Aurelia 1000.*Vorlage 1 laden/ }).click();
    await restored.getByRole('switch', { name: 'Hydrofoils aktivieren' }).click();
    await restored.getByRole('button', { name: 'Einzelfoils konfigurieren', exact: true }).click();
    for (let index = 0; index < 4; index++) await restored.getByRole('button', { name: 'Foil hinzufügen', exact: true }).click();
    assert.equal(await restored.locator('#selected-foil option').count(), 6);
    assert.equal(await restored.getByRole('button', { name: 'Foil hinzufügen', exact: true }).isDisabled(), true);
    const setPosition = async (name, value) => {
      const input = restored.getByRole('spinbutton', { name });
      await input.fill(value);
      await input.press('Tab');
    };
    await setPosition(/Längsposition ab Bug/, '650');
    await setPosition(/Querposition zur Rumpfmitte/, '-75');
    await setPosition(/Eintauchtiefe/, '180');
    await setPosition(/Drehwinkel/, '15');
    await restored.getByRole('button', { name: 'L-Foil', exact: true }).click();
    await restored.getByRole('slider', { name: 'Foil-Anstellwinkel' }).fill('6');
    const foilFile = path.join(folder, 'six-foils.json');
    await desktop.evaluate(({ dialog }, filename) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename });
    }, foilFile);
    await restored.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
    await restored.getByRole('button', { name: 'Gespeichert', exact: true }).waitFor();
    const foilDesign = JSON.parse(await fs.readFile(foilFile, 'utf8'));
    assert.equal(foilDesign.foils.items.length, 6);
    const last = foilDesign.foils.items[5];
    assert.equal(last.position, 65);
    assert.equal(last.lateral, -0.075);
    assert.equal(last.immersion, 0.18);
    assert.equal(last.yaw, 15);
    assert.equal(last.type, 'L');
    assert.equal(last.incidence, 6);
    assert.equal(await restored.locator('.foil-analysis-table tbody tr').count(), 6);
    await restored.getByRole('button', { name: 'Foil entfernen', exact: true }).click();
    assert.equal(await restored.locator('#selected-foil option').count(), 5);
    await restored.getByRole('button', { name: 'Rückgängig', exact: true }).click();
    assert.equal(await restored.locator('#selected-foil option').count(), 6);
    await restored.waitForFunction(() => JSON.parse(localStorage.getItem('sailor-studio.design.v1') || '{}').foils?.items?.length === 6);
    await restored.reload();
    await restored.getByRole('button', { name: 'Foils', exact: true }).click();
    await restored.getByRole('combobox', { name: 'Foil auswählen' }).selectOption(last.id);
    assert.equal(await restored.getByRole('spinbutton', { name: /Längsposition ab Bug/ }).inputValue(), '650');
    assert.equal(await restored.getByRole('spinbutton', { name: /Querposition zur Rumpfmitte/ }).inputValue(), '-75');
    assert.equal(await restored.getByRole('spinbutton', { name: /Drehwinkel/ }).inputValue(), '15');
    assert.equal(await restored.getByRole('checkbox', { name: 'Hydrofoils aktivieren', exact: true }).isChecked(), true);
    await restored.getByRole('button', { name: 'Balance', exact: true }).click();
    await setPosition(/Schwerpunkt längs/, '-35');
    await setPosition(/Schwerpunkt Höhe/, '-90');
    await setPosition(/Schwerpunkt quer/, '12');
    await restored.locator('.balance-panel[aria-busy="false"]').waitFor();
    assert.match(await restored.locator('.balance-center-line').innerText(), /CG: X -35.*Y -90.*Z 12/);
    const previewSpeed = restored.getByRole('slider', { name: 'Vorschaugeschwindigkeit', exact: true });
    await previewSpeed.fill('1');
    await restored.locator('.balance-panel[aria-busy="false"]').waitFor();
    const forceBefore = await restored.locator('.balance-stats strong').nth(1).innerText();
    await previewSpeed.fill('3');
    await restored.locator('.balance-panel[aria-busy="false"]').waitFor();
    assert.notEqual(await restored.locator('.balance-stats strong').nth(1).innerText(), forceBefore);
    await restored.waitForFunction(() => document.querySelector('.balance-curves polyline')?.getAttribute('points')?.split(' ').length === 21);
    assert.equal(await restored.locator('.balance-curves polyline').count(), 5);
    await restored.getByRole('button', { name: 'Geschwindigkeitsverlauf abspielen', exact: true }).click();
    await restored.waitForFunction(() => Number(document.querySelector('#balance-speed').value) > 3);
    await restored.getByRole('button', { name: 'Geschwindigkeitsverlauf pausieren', exact: true }).click();
    await restored.getByRole('button', { name: 'Zur Entwurfsgeschwindigkeit', exact: true }).click();
    assert.equal(await previewSpeed.inputValue(), '1');
    await previewSpeed.fill('5');
    await restored.locator('.balance-panel[aria-busy="false"]').waitFor();
    await restored.waitForFunction(() => document.querySelector('.balance-status')?.textContent === 'Foil-Flugbereich: nicht bewertet');
    assert.match(await restored.locator('.balance-stats').innerText(), /Nicht bewertbar/);
    const flightWarnings = await restored.locator('.balance-panel .analysis-warnings').innerText();
    assert.match(flightWarnings, /Fluglage/);
    assert.doesNotMatch(flightWarnings, /Froude|Rueckstellsteifigkeit/);
    await restored.waitForFunction(() => document.querySelector('[aria-label="Strömungsanalyse"] .analysis-stats')?.textContent.includes('Nicht anwendbar'));
    await restored.getByRole('button', { name: 'Zur Entwurfsgeschwindigkeit', exact: true }).click();
    await restored.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
    await restored.getByRole('button', { name: 'Gespeichert', exact: true }).waitFor();
    const balanceDesign = JSON.parse(await fs.readFile(foilFile, 'utf8'));
    assert.deepEqual(balanceDesign.massCenter, { x: -0.035, y: -0.09, z: 0.012 });
    assert.equal(balanceDesign.flow.speed, 1);
    await restored.waitForFunction(() => JSON.parse(localStorage.getItem('sailor-studio.design.v1') || '{}').massCenter?.x === -0.035);
    await restored.reload();
    await restored.getByRole('button', { name: 'Balance', exact: true }).click();
    assert.equal(await restored.getByRole('spinbutton', { name: /Schwerpunkt längs/ }).inputValue(), '-35');
    assert.equal(await restored.getByRole('spinbutton', { name: /Schwerpunkt Höhe/ }).inputValue(), '-90');
    assert.equal(await restored.getByRole('spinbutton', { name: /Schwerpunkt quer/ }).inputValue(), '12');
    assert.equal(await restored.locator('.scene-error').count(), 0);
    await restored.getByRole('button', { name: 'Rumpf', exact: true }).click();
    await restored.getByRole('button', { name: 'Trimaran', exact: true }).click();
    await restored.getByRole('slider', { name: 'Länge Hauptrumpf', exact: true }).fill('0.9');
    await restored.getByRole('slider', { name: 'Länge Ausleger Backbord', exact: true }).fill('0.65');
    await restored.getByRole('slider', { name: 'Länge Ausleger Steuerbord', exact: true }).fill('1.3');
    await restored.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
    await restored.getByRole('button', { name: 'Gespeichert', exact: true }).waitFor();
    const triDesign = JSON.parse(await fs.readFile(foilFile, 'utf8'));
    assert.deepEqual(triDesign.hullLengths, [0.9, 0.65, 1.3]);
    assert.equal(triDesign.length, 1.3);
    assert.ok(triDesign.mass <= 10);
    await restored.waitForFunction(() => JSON.parse(localStorage.getItem('sailor-studio.design.v1') || '{}').hullLengths?.[2] === 1.3);
    await restored.reload();
    assert.equal(await restored.getByRole('slider', { name: 'Länge Hauptrumpf', exact: true }).inputValue(), '0.9');
    assert.equal(await restored.getByRole('slider', { name: 'Länge Ausleger Backbord', exact: true }).inputValue(), '0.65');
    assert.equal(await restored.getByRole('slider', { name: 'Länge Ausleger Steuerbord', exact: true }).inputValue(), '1.3');
  } finally {
    if (desktop) await desktop.close();
    await fs.rm(folder, { recursive: true, force: true });
  }
});
